const LEGACY_SUGGESTED_POSITIONING =
  'MessMind helps college hostel messes make smarter meal-preparation decisions by combining student meal responses, historical consumption and demand forecasting into one centralized platform, reducing avoidable food wastage and improving kitchen planning.';

function isUnmodifiedAutoGeneratedSample(raw: Record<string, unknown>): boolean {
  const id = typeof raw.id === 'string' ? raw.id : '';
  const sample = AUTO_GENERATED_SAMPLES[id];
  if (!sample) return false;
  return (
    raw.name === sample.name &&
    raw.strengths === sample.strengths &&
    raw.weaknesses === sample.weaknesses
  );
}

function normalizeEvidenceQuality(rawValue: unknown): EvidenceQuality | '' {
  if (rawValue === 'Strong' || rawValue === 'Moderate' || rawValue === 'Weak') {
    return rawValue;
  }
  return '';
}

function normalizeAlternativeType(rawValue: unknown): AlternativeType | '' {
  if (
    rawValue === 'Direct Competitor' ||
    rawValue === 'Indirect Competitor' ||
    rawValue === 'Substitute' ||
    rawValue === 'Do Nothing'
  ) {
    return rawValue;
  }
  if (rawValue === 'Indirect Substitute') return 'Indirect Competitor';
  if (rawValue === 'Manual / In-House Process') return 'Substitute';
  return '';
}

function normalizeAlternativeRecord(
  raw: Record<string, unknown>,
  isLegacyVersion: boolean
): AlternativeRecord {
  const emptyMatrix = createEmptyMatrixRatings();
  const rawMatrix =
    raw.matrixRatings && typeof raw.matrixRatings === 'object'
      ? (raw.matrixRatings as Record<string, unknown>)
      : {};

  const matrixRatings = { ...emptyMatrix };
  (Object.keys(emptyMatrix) as MatrixCriterionId[]).forEach((key) => {
    const val = rawMatrix[key];
    if (val === 1 || val === 2 || val === 3 || val === 4 || val === 5) {
      matrixRatings[key] = val;
    } else {
      matrixRatings[key] = null;
    }
  });

  const rawThreat = raw.threatScore;
  const threatScore =
    rawThreat === 1 ||
    rawThreat === 2 ||
    rawThreat === 3 ||
    rawThreat === 4 ||
    rawThreat === 5
      ? rawThreat
      : null;

  const rawPos = raw.position as Record<string, unknown> | null | undefined;
  const position =
    rawPos &&
    typeof rawPos.x === 'number' &&
    typeof rawPos.y === 'number'
      ? { x: rawPos.x, y: rawPos.y }
      : null;

  return {
    id:
      typeof raw.id === 'string' && raw.id
        ? raw.id
        : `alt-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
    name: typeof raw.name === 'string' ? raw.name : '',
    type: normalizeAlternativeType(raw.type ?? raw.classification),
    approximatePrice:
      typeof raw.approximatePrice === 'string' ? raw.approximatePrice : '',
    mainOffer:
      typeof raw.mainOffer === 'string'
        ? raw.mainOffer
        : typeof raw.mainFeatures === 'string'
          ? raw.mainFeatures
          : '',
    strengths: typeof raw.strengths === 'string' ? raw.strengths : '',
    weaknesses: typeof raw.weaknesses === 'string' ? raw.weaknesses : '',
    evidenceSource:
      typeof raw.evidenceSource === 'string' ? raw.evidenceSource : '',
    evidenceQuality: normalizeEvidenceQuality(
      raw.evidenceQuality ?? (isLegacyVersion ? raw.evidenceStrength : '')
    ),
    threatScore,
    matrixRatings,
    position,
  };
}

function isLegacyDefaultMessMindMatrix(
  rawRatings: Record<string, unknown>
): boolean {
  return (
    rawRatings.ai_demand_forecasting === 5 &&
    rawRatings.student_meal_response === 5 &&
    rawRatings.historical_consumption === 4 &&
    rawRatings.recommended_prep_quantities === 5 &&
    rawRatings.food_waste_tracking === 4 &&
    rawRatings.institutional_mess_mgmt === 4 &&
    rawRatings.reporting_analytics === 4
  );
}

function normalizePositioningStatement(
  rawStmt: unknown,
  targetCustomer: string,
  alternatives: AlternativeRecord[]
): PositioningStatementData {
  const base = createInitialPositioningStatement(targetCustomer);
  if (!rawStmt || typeof rawStmt !== 'object') {
    return base;
  }

  const raw = rawStmt as Record<string, unknown>;
  const normalizedTarget =
    typeof raw.targetCustomer === 'string' && raw.targetCustomer.trim()
      ? raw.targetCustomer
      : targetCustomer;
  const categorySolution =
    typeof raw.categorySolution === 'string' ? raw.categorySolution : '';
  const primaryBenefit =
    typeof raw.primaryBenefit === 'string' ? raw.primaryBenefit : '';
  const rawAltId =
    typeof raw.mainAlternativeId === 'string' ? raw.mainAlternativeId : '';
  const matchedAlt = alternatives.find((a) => a.id === rawAltId);
  const mainAlternativeId = matchedAlt ? rawAltId : '';
  const reasonToBelieve =
    typeof raw.reasonToBelieve === 'string' ? raw.reasonToBelieve : '';

  const statementText =
    typeof raw.statementText === 'string' && raw.statementText.trim()
      ? raw.statementText
      : formatPositioningStatement({
          targetCustomer: normalizedTarget,
          categorySolution,
          primaryBenefit,
          mainAlternativeName: matchedAlt?.name ?? '',
          reasonToBelieve,
        });

  const evaluations = Array.isArray(raw.evaluations)
    ? (raw.evaluations as StatementDimensionEvaluation[])
    : [];

  return {
    targetCustomer: normalizedTarget,
    categorySolution,
    primaryBenefit,
    mainAlternativeId,
    reasonToBelieve,
    statementText,
    evaluations,
    saved: Boolean(raw.saved),
    savedAt: typeof raw.savedAt === 'string' ? raw.savedAt : null,
  };
}

function normalizeAIStrategyChallenge(
  rawChallenge: unknown
): AIStrategyChallengeData {
  const base = createInitialAIStrategyChallenge();
  if (!rawChallenge || typeof rawChallenge !== 'object') {
    return base;
  }
  const raw = rawChallenge as Record<string, unknown>;
  const rawChallenges = Array.isArray(raw.challenges)
    ? (raw.challenges as Record<string, unknown>[])
    : [];

  const challenges: StrategyChallengeItem[] = rawChallenges
    .filter((item) => item && typeof item === 'object')
    .map((item, idx) => {
      const rawFb =
        item.feedback && typeof item.feedback === 'object'
          ? (item.feedback as Record<string, unknown>)
          : null;
      const feedback: StrategyChallengeFeedback | null =
        rawFb &&
        typeof rawFb.supported === 'string' &&
        typeof rawFb.assumption === 'string' &&
        typeof rawFb.nextEvidenceNeeded === 'string'
          ? {
              supported: rawFb.supported,
              assumption: rawFb.assumption,
              nextEvidenceNeeded: rawFb.nextEvidenceNeeded,
              generatedAt:
                typeof rawFb.generatedAt === 'string'
                  ? rawFb.generatedAt
                  : new Date().toISOString(),
            }
          : null;

      return {
        id:
          typeof item.id === 'string' && item.id
            ? item.id
            : `challenge-${idx + 1}`,
        focusArea:
          typeof item.focusArea === 'string' ? item.focusArea : 'Strategy',
        question: typeof item.question === 'string' ? item.question : '',
        contextBasis:
          typeof item.contextBasis === 'string' ? item.contextBasis : '',
        userResponse:
          typeof item.userResponse === 'string' ? item.userResponse : '',
        feedback,
      };
    });

  const rawRev =
    raw.review && typeof raw.review === 'object'
      ? (raw.review as Record<string, unknown>)
      : null;

  const review: StrategyChallengeReview | null =
    rawRev &&
    typeof rawRev.strongestPart === 'string' &&
    typeof rawRev.biggestAssumption === 'string' &&
    typeof rawRev.nextValidationPriority === 'string'
      ? {
          strongestPart: rawRev.strongestPart,
          biggestAssumption: rawRev.biggestAssumption,
          nextValidationPriority: rawRev.nextValidationPriority,
          generatedAt:
            typeof rawRev.generatedAt === 'string'
              ? rawRev.generatedAt
              : new Date().toISOString(),
        }
      : null;

  const maxIdx = Math.max(0, challenges.length - 1);
  const currentIndex =
    typeof raw.currentIndex === 'number'
      ? Math.max(0, Math.min(maxIdx, Math.floor(raw.currentIndex)))
      : 0;

  return {
    challenges,
    currentIndex,
    review,
    completed: Boolean(raw.completed),
    completedAt: typeof raw.completedAt === 'string' ? raw.completedAt : null,
    generatedAt: typeof raw.generatedAt === 'string' ? raw.generatedAt : null,
  };
}

function normalizeStage1Data(
  rawStage1?: Record<string, unknown> | null,
  version = 6,
  targetCustomer?: string
): Stage1Data {
  const fallback = createInitialStage1Data(targetCustomer);
  if (!rawStage1 || typeof rawStage1 !== 'object') {
    return fallback;
  }

  const isPreV3 = version < 3;
  const isPreV4 = version < 4;

  const rawAlts = Array.isArray(rawStage1.alternatives)
    ? (rawStage1.alternatives as Record<string, unknown>[])
    : [];

  let processedAlts: AlternativeRecord[];
  if (isPreV3) {
    processedAlts = rawAlts
      .filter((alt) => !isUnmodifiedAutoGeneratedSample(alt))
      .map((alt) => normalizeAlternativeRecord(alt, true));

    if (processedAlts.length === 0) {
      processedAlts = createInitialBlankAlternatives();
    }
  } else {
    processedAlts =
      rawAlts.length > 0
        ? rawAlts.map((alt) => normalizeAlternativeRecord(alt, false))
        : createInitialBlankAlternatives();
  }

  const rawMessRatings =
    rawStage1.messMindMatrixRatings &&
    typeof rawStage1.messMindMatrixRatings === 'object'
      ? (rawStage1.messMindMatrixRatings as Record<string, unknown>)
      : {};

  const messMindMatrixRatings = createEmptyMatrixRatings();
  if (!isPreV3 || !isLegacyDefaultMessMindMatrix(rawMessRatings)) {
    (Object.keys(messMindMatrixRatings) as MatrixCriterionId[]).forEach(
      (key) => {
        const val = rawMessRatings[key];
        if (val === 1 || val === 2 || val === 3 || val === 4 || val === 5) {
          messMindMatrixRatings[key] = val;
        }
      }
    );
  }

  const rawDiff =
    rawStage1.differentiation && typeof rawStage1.differentiation === 'object'
      ? (rawStage1.differentiation as Partial<DifferentiationProfile>)
      : {};

  // Clear unmodified auto-generated positioning statement / moat claims on v4 upgrade
  const differentiation: DifferentiationProfile =
    isPreV4 && rawDiff.positioningStatement === LEGACY_SUGGESTED_POSITIONING
      ? createEmptyDifferentiation()
      : {
          ...createEmptyDifferentiation(),
          ...rawDiff,
        };

  const rawPos =
    rawStage1.messMindPosition && typeof rawStage1.messMindPosition === 'object'
      ? (rawStage1.messMindPosition as Partial<StrategicCoordinate>)
      : null;

  const messMindPosition =
    isPreV4 && rawPos && rawPos.x === 84 && rawPos.y === 86
      ? null
      : rawPos && typeof rawPos.x === 'number' && typeof rawPos.y === 'number'
        ? { x: rawPos.x, y: rawPos.y }
        : null;

  const alternativesSlice = processedAlts.slice(0, MAX_ALTERNATIVES);

  return {
    alternatives: alternativesSlice,
    messMindMatrixRatings,
    messMindPosition,
    differentiation,
    positioningStatement: normalizePositioningStatement(
      rawStage1.positioningStatement,
      targetCustomer ?? fallback.positioningStatement.targetCustomer,
      alternativesSlice
    ),
    aiStrategyChallenge: normalizeAIStrategyChallenge(
      rawStage1.aiStrategyChallenge
    ),
    criticalAssumption:
      typeof rawStage1.criticalAssumption === 'string' && !isPreV4
        ? rawStage1.criticalAssumption
        : '',
    completed: Boolean(rawStage1.completed),
    completedAt:
      typeof rawStage1.completedAt === 'string' ? rawStage1.completedAt : null,
  };
}

function normalizeStudioState(parsed: Record<string, unknown>): VentureStudioState {
  const fallback = createInitialStudioState();

  if (!parsed || typeof parsed !== 'object') {
    return fallback;
  }

  const version = typeof parsed.version === 'number' ? parsed.version : 1;

    if (!Array.isArray(parsed.ventures) && parsed.stage1) {
      const legacyProfile = (parsed.ventureProfile ?? {}) as Partial<VentureProfile>;
      const legacyFuture = (parsed.futureStages ?? {}) as Partial<
        VentureWorkspace['futureStages']
      >;
      const baseMessMind = createInitialMessMindWorkspace();

      const normalizedProfile: VentureProfile = {
        ...baseMessMind.ventureProfile,
        ...legacyProfile,
      };

      const migratedVenture: VentureWorkspace = {
        id: 'messmind',
        ventureProfile: normalizedProfile,
        stage1: normalizeStage1Data(
          parsed.stage1 as Record<string, unknown>,
          version,
          normalizedProfile.targetCustomer
        ),
        futureStages: {
          ...baseMessMind.futureStages,
          ...legacyFuture,
        },
      };

      return {
        version: 6,
        activeView: 'venture-bank',
        selectedStageId:
          (parsed.selectedStageId as StageId | undefined) ?? 'stage-1',
        selectedVentureId: 'messmind',
        ventures: [migratedVenture],
        lastSavedAt:
          typeof parsed.lastSavedAt === 'string'
            ? parsed.lastSavedAt
            : new Date().toISOString(),
      };
    }

    const rawVentures = Array.isArray(parsed.ventures)
      ? (parsed.ventures as Record<string, unknown>[])
      : [];

    const normalizedVentures: VentureWorkspace[] =
      rawVentures.length > 0
        ? rawVentures.map((v, index) => {
            const base = createInitialMessMindWorkspace();
            const id =
              typeof v.id === 'string' && v.id.trim()
                ? v.id
                : `venture-${index + 1}`;
            const normalizedProfile: VentureProfile = {
              ...base.ventureProfile,
              ...((v.ventureProfile as Partial<VentureProfile>) ?? {}),
            };
            return {
              id,
              ventureProfile: normalizedProfile,
              stage1: normalizeStage1Data(
                (v.stage1 as Record<string, unknown>) ?? null,
                version,
                normalizedProfile.targetCustomer
              ),
              futureStages: {
                ...base.futureStages,
                ...((v.futureStages as Partial<
                  VentureWorkspace['futureStages']
                >) ?? {}),
              },
            };
          })
        : fallback.ventures;

    const storedSelectedId =
      typeof parsed.selectedVentureId === 'string' ||
      parsed.selectedVentureId === null
        ? parsed.selectedVentureId
        : fallback.selectedVentureId;

    const validSelectedId =
      storedSelectedId &&
      normalizedVentures.some((v) => v.id === storedSelectedId)
        ? storedSelectedId
        : normalizedVentures[0]?.id ?? null;

    const activeView: WorkspaceView =
      parsed.activeView === 'competition-lab'
        ? 'competition-lab'
        : 'venture-bank';

    return {
      version: 6,
      activeView: validSelectedId ? activeView : 'venture-bank',
      selectedStageId:
        (parsed.selectedStageId as StageId | undefined) ?? 'stage-1',
      selectedVentureId: validSelectedId,
      ventures: normalizedVentures,
      lastSavedAt:
        typeof parsed.lastSavedAt === 'string'
          ? parsed.lastSavedAt
          : new Date().toISOString(),
    };
}

function loadStudioState(): VentureStudioState {
  if (typeof window === 'undefined') {
    return createInitialStudioState();
  }
  try {
    const raw = window.localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      return createInitialStudioState();
    }
    const parsed = JSON.parse(raw) as Record<string, unknown>;
    return normalizeStudioState(parsed);
  } catch {
    return createInitialStudioState();
  }
}

function sanitizeForFirestore<T>(value: T): T {
  if (Array.isArray(value)) {
    return value.map((item) => sanitizeForFirestore(item)) as unknown as T;
  }
  if (value && typeof value === 'object') {
    const out: Record<string, unknown> = {};
    for (const [key, val] of Object.entries(value as Record<string, unknown>)) {
      if (val !== undefined) {
        out[key] = sanitizeForFirestore(val);
      }
    }
    return out as T;
  }
  return value;
}

export function isAlternativePopulated(alt: AlternativeRecord): boolean {
  return Boolean(
    alt.name.trim() ||
      alt.type ||
      alt.approximatePrice.trim() ||
      alt.mainOffer.trim() ||
      alt.strengths.trim() ||
      alt.weaknesses.trim() ||
      alt.evidenceSource.trim() ||
      alt.evidenceQuality
  );
}

// Strict Section 5 Completion Rule
export function isAlternativeCompleted(alt: AlternativeRecord): boolean {
  return Boolean(
    alt.name.trim() &&
      alt.type &&
      alt.mainOffer.trim() &&
      alt.strengths.trim() &&
      alt.weaknesses.trim() &&
      alt.evidenceSource.trim() &&
      alt.evidenceQuality
  );
}

export function hasVentureResearch(venture: VentureWorkspace | null): boolean {
  if (!venture) return false;
  return (
    venture.stage1.alternatives.some(isAlternativePopulated) ||
    venture.stage1.completed ||
    venture.stage1.positioningStatement.saved ||
    venture.stage1.aiStrategyChallenge.challenges.length > 0 ||
    Object.values(venture.stage1.messMindMatrixRatings).some((v) => v !== null)
  );
}

export function useVentureStudio() {
  const { user, authReady, profileSyncedUid } = useAuth();
  const [state, setState] = useState<VentureStudioState>(() => loadStudioState());
  const [saveFeedback, setSaveFeedback] = useState<string | null>(null);
  const [cloudSynced, setCloudSynced] = useState(false);
  const [fatalSyncError, setFatalSyncError] = useState<Error | null>(null);

  if (fatalSyncError) {
    throw fatalSyncError;
  }

  const stateRef = useRef(state);
  stateRef.current = state;

  const cloudInitializedUidRef = useRef<string | null>(null);
  const lastWrittenTimestampRef = useRef<string | null>(null);
  const lastAppliedCloudTimestampRef = useRef<string | null>(null);

  const persistState = useCallback((nextState: VentureStudioState) => {
    try {
      window.localStorage.setItem(STORAGE_KEY, JSON.stringify(nextState));
    } catch {
      // Ignore storage quota errors gracefully
    }
  }, []);

  useEffect(() => {
    persistState(state);
  }, [state, persistState]);

  // Subscribe to per-user Firestore workspace when Google Sign-In is active & verified
  useEffect(() => {
    if (!authReady || !user || !user.emailVerified || profileSyncedUid !== user.uid) {
      cloudInitializedUidRef.current = null;
      setCloudSynced(false);
      return;
    }

    const docPath = `users/${user.uid}/studio/workspace`;
    const workspaceRef = doc(db, 'users', user.uid, 'studio', 'workspace');

    const unsubscribe = onSnapshot(
      workspaceRef,
      async (snapshot) => {
        if (!snapshot.exists()) {
          const current = stateRef.current;
          const createPayload = sanitizeForFirestore({
            ownerId: user.uid,
            version: current.version,
            activeView: current.activeView,
            selectedStageId: current.selectedStageId,
            selectedVentureId: (current.selectedVentureId ?? '').slice(0, 128),
            ventures: current.ventures.slice(0, 10),
            lastSavedAt: current.lastSavedAt.slice(0, 64),
          });
          lastWrittenTimestampRef.current = current.lastSavedAt;
          try {
            await setDoc(workspaceRef, {
              ...createPayload,
              createdAt: serverTimestamp(),
              updatedAt: serverTimestamp(),
            });
            cloudInitializedUidRef.current = user.uid;
            setCloudSynced(true);
          } catch (error) {
            try {
              handleFirestoreError(error, OperationType.CREATE, docPath);
            } catch (wrapped) {
              setFatalSyncError(wrapped as Error);
            }
          }
          return;
        }

        if (snapshot.metadata.hasPendingWrites) {
          cloudInitializedUidRef.current = user.uid;
          setCloudSynced(true);
          return;
        }

        const raw = snapshot.data() as Record<string, unknown>;
        const cloudSavedAt =
          typeof raw.lastSavedAt === 'string' ? raw.lastSavedAt : '';

        if (
          cloudSavedAt &&
          (cloudSavedAt === lastWrittenTimestampRef.current ||
            cloudSavedAt === lastAppliedCloudTimestampRef.current)
        ) {
          cloudInitializedUidRef.current = user.uid;
          setCloudSynced(true);
          return;
        }

        const normalized = normalizeStudioState({
          ...raw,
          selectedVentureId:
            typeof raw.selectedVentureId === 'string' &&
            raw.selectedVentureId.trim()
              ? raw.selectedVentureId
              : null,
        });
        lastAppliedCloudTimestampRef.current = normalized.lastSavedAt;
        cloudInitializedUidRef.current = user.uid;
        setState(normalized);
        setCloudSynced(true);
      },
      (error) => {
        try {
          handleFirestoreError(error, OperationType.GET, docPath);
        } catch (wrapped) {
          setFatalSyncError(wrapped as Error);
        }
      }
    );

    return () => {
      unsubscribe();
    };
  }, [authReady, user, profileSyncedUid]);

  // Persist local mutations to Firestore when signed in and initialized
  useEffect(() => {
    if (
      !authReady ||
      !user ||
      !user.emailVerified ||
      profileSyncedUid !== user.uid ||
      cloudInitializedUidRef.current !== user.uid
    ) {
      return;
    }

    if (state.lastSavedAt === lastAppliedCloudTimestampRef.current) {
      return;
    }

    const timer = window.setTimeout(async () => {
      const docPath = `users/${user.uid}/studio/workspace`;
      const workspaceRef = doc(db, 'users', user.uid, 'studio', 'workspace');
      const updatePayload = sanitizeForFirestore({
        version: state.version,
        activeView: state.activeView,
        selectedStageId: state.selectedStageId,
        selectedVentureId: (state.selectedVentureId ?? '').slice(0, 128),
        ventures: state.ventures.slice(0, 10),
        lastSavedAt: state.lastSavedAt.slice(0, 64),
      });
      lastWrittenTimestampRef.current = state.lastSavedAt;

      try {
        await updateDoc(workspaceRef, {
          ...updatePayload,
          updatedAt: serverTimestamp(),
        });
      } catch (error) {
        try {
          handleFirestoreError(error, OperationType.UPDATE, docPath);
        } catch (wrapped) {
          setFatalSyncError(wrapped as Error);
        }
      }
    }, 350);

    return () => window.clearTimeout(timer);
  }, [state, authReady, user, profileSyncedUid]);

  const notifySaved = useCallback((message: string) => {
    setSaveFeedback(message);
  }, []);

  useEffect(() => {
    if (!saveFeedback) return;
    const timer = window.setTimeout(() => {
      setSaveFeedback(null);
    }, 3200);
    return () => window.clearTimeout(timer);
  }, [saveFeedback]);

  const selectedVenture = useMemo<VentureWorkspace | null>(() => {
    if (!state.selectedVentureId) return null;
    return (
      state.ventures.find((v) => v.id === state.selectedVentureId) ??
      state.ventures[0] ??
      null
    );
  }, [state.ventures, state.selectedVentureId]);

  const updateState = useCallback(
    (
      updater: (prev: VentureStudioState) => VentureStudioState,
      feedbackMessage?: string
    ) => {
      setState((prev) => {
        const updated = updater(prev);
        return {
          ...updated,
          lastSavedAt: new Date().toISOString(),
        };
      });
      if (feedbackMessage) {
        notifySaved(feedbackMessage);
      }
    },
    [notifySaved]
  );

  const updateSelectedVenture = useCallback(
    (
      updater: (venture: VentureWorkspace) => VentureWorkspace,
      feedbackMessage?: string
    ) => {
      updateState((prev) => {
        const targetId = prev.selectedVentureId ?? prev.ventures[0]?.id;
        if (!targetId) return prev;
        return {
          ...prev,
          ventures: prev.ventures.map((venture) =>
            venture.id === targetId ? updater(venture) : venture
          ),
        };
      }, feedbackMessage);
    },
    [updateState]
  );

  const selectVenture = useCallback(
    (ventureId: string) => {
      updateState((prev) => {
        const exists = prev.ventures.some((v) => v.id === ventureId);
        if (!exists) return prev;
        return {
          ...prev,
          selectedVentureId: ventureId,
        };
      }, 'Selected venture updated');
    },
    [updateState]
  );

  const setActiveView = useCallback(
    (view: WorkspaceView) => {
      updateState((prev) => ({
        ...prev,
        activeView: view,
      }));
    },
    [updateState]
  );

  const setSelectedStage = useCallback(
    (stageId: StageId) => {
      updateState((prev) => ({
        ...prev,
        selectedStageId: stageId,
      }));
    },
    [updateState]
  );

  const saveVentureProfile = useCallback(
    (profile: VentureProfile) => {
      updateSelectedVenture(
        (venture) => {
          const prevStmt = venture.stage1.positioningStatement;
          const shouldSyncTarget =
            !prevStmt.targetCustomer.trim() ||
            prevStmt.targetCustomer === venture.ventureProfile.targetCustomer;
          const nextTarget = shouldSyncTarget
            ? profile.targetCustomer
            : prevStmt.targetCustomer;
          const matchedAlt = venture.stage1.alternatives.find(
            (a) => a.id === prevStmt.mainAlternativeId
          );
          return {
            ...venture,
            ventureProfile: profile,
            stage1: {
              ...venture.stage1,
              positioningStatement: shouldSyncTarget
                ? {
                    ...prevStmt,
                    targetCustomer: nextTarget,
                    statementText: formatPositioningStatement({
                      targetCustomer: nextTarget,
                      categorySolution: prevStmt.categorySolution,
                      primaryBenefit: prevStmt.primaryBenefit,
                      mainAlternativeName: matchedAlt?.name ?? '',
                      reasonToBelieve: prevStmt.reasonToBelieve,
                    }),
                  }
                : prevStmt,
            },
          };
        },
        'Venture profile saved'
      );
    },
    [updateSelectedVenture]
  );

  const addBlankAlternative = useCallback(() => {
    updateSelectedVenture((venture) => {
      if (venture.stage1.alternatives.length >= MAX_ALTERNATIVES) {
        return venture;
      }
      return {
        ...venture,
        stage1: {
          ...venture.stage1,
          alternatives: [
            ...venture.stage1.alternatives,
            createBlankAlternative(),
          ],
        },
      };
    }, 'Blank alternative slot added');
  }, [updateSelectedVenture]);

  const updateAlternative = useCallback(
    (updatedAlt: AlternativeRecord, feedbackMessage = 'Alternative saved') => {
      updateSelectedVenture(
        (venture) => ({
          ...venture,
          stage1: {
            ...venture.stage1,
            alternatives: venture.stage1.alternatives.map((alt) =>
              alt.id === updatedAlt.id ? updatedAlt : alt
            ),
          },
        }),
        feedbackMessage
      );
    },
    [updateSelectedVenture]
  );

  const deleteAlternative = useCallback(
    (id: string) => {
      updateSelectedVenture(
        (venture) => ({
          ...venture,
          stage1: {
            ...venture.stage1,
            alternatives: venture.stage1.alternatives.filter(
              (alt) => alt.id !== id
            ),
          },
        }),
        'Alternative removed'
      );
    },
    [updateSelectedVenture]
  );

  const updateMessMindMatrixRating = useCallback(
    (criterionId: MatrixCriterionId, rating: MatrixRatingValue) => {
      updateSelectedVenture(
        (venture) => ({
          ...venture,
          stage1: {
            ...venture.stage1,
            messMindMatrixRatings: {
              ...venture.stage1.messMindMatrixRatings,
              [criterionId]: rating,
            },
          },
        }),
        'Matrix entry saved'
      );
    },
    [updateSelectedVenture]
  );

  const updateAlternativeMatrixRating = useCallback(
    (
      alternativeId: string,
      criterionId: MatrixCriterionId,
      rating: MatrixRatingValue
    ) => {
      updateSelectedVenture(
        (venture) => ({
          ...venture,
          stage1: {
            ...venture.stage1,
            alternatives: venture.stage1.alternatives.map((alt) =>
              alt.id === alternativeId
                ? {
                    ...alt,
                    matrixRatings: {
                      ...alt.matrixRatings,
                      [criterionId]: rating,
                    },
                  }
                : alt
            ),
          },
        }),
        'Matrix entry saved'
      );
    },
    [updateSelectedVenture]
  );

  const saveDifferentiation = useCallback(
    (differentiation: DifferentiationProfile) => {
      updateSelectedVenture(
        (venture) => ({
          ...venture,
          stage1: {
            ...venture.stage1,
            differentiation,
          },
        }),
        'Differentiation saved'
      );
    },
    [updateSelectedVenture]
  );

  const updateMessMindPosition = useCallback(
    (position: StrategicCoordinate, showFeedback = false) => {
      updateSelectedVenture(
        (venture) => ({
          ...venture,
          stage1: {
            ...venture.stage1,
            messMindPosition: position,
          },
        }),
        showFeedback ? 'MessMind strategic position saved' : undefined
      );
    },
    [updateSelectedVenture]
  );

  const updateAlternativePosition = useCallback(
    (
      alternativeId: string,
      position: StrategicCoordinate,
      showFeedback = false
    ) => {
      updateSelectedVenture(
        (venture) => ({
          ...venture,
          stage1: {
            ...venture.stage1,
            alternatives: venture.stage1.alternatives.map((alt) =>
              alt.id === alternativeId ? { ...alt, position } : alt
            ),
          },
        }),
        showFeedback ? 'Alternative strategic position saved' : undefined
      );
    },
    [updateSelectedVenture]
  );

  const updateCriticalAssumption = useCallback(
    (criticalAssumption: string) => {
      updateSelectedVenture(
        (venture) => ({
          ...venture,
          stage1: {
            ...venture.stage1,
            criticalAssumption,
          },
        }),
        'Validation assumption saved'
      );
    },
    [updateSelectedVenture]
  );

  const toggleStage1Completion = useCallback(
    (complete: boolean) => {
      updateSelectedVenture(
        (venture) => ({
          ...venture,
          stage1: {
            ...venture.stage1,
            completed: complete,
            completedAt: complete ? new Date().toISOString() : null,
          },
        }),
        complete
          ? 'Stage 1 marked as complete'
          : 'Stage 1 reopened for editing'
      );
    },
    [updateSelectedVenture]
  );

  const updatePositioningStatementDraft = useCallback(
    (positioningStatement: PositioningStatementData) => {
      updateSelectedVenture((venture) => ({
        ...venture,
        stage1: {
          ...venture.stage1,
          positioningStatement,
        },
      }));
    },
    [updateSelectedVenture]
  );

  const savePositioningStatement = useCallback(
    (positioningStatement: PositioningStatementData) => {
      updateSelectedVenture(
        (venture) => ({
          ...venture,
          stage1: {
            ...venture.stage1,
            positioningStatement: {
              ...positioningStatement,
              saved: true,
              savedAt: new Date().toISOString(),
            },
          },
        }),
        'Positioning statement saved'
      );
    },
    [updateSelectedVenture]
  );

  const updateAIStrategyChallenge = useCallback(
    (
      aiStrategyChallenge: AIStrategyChallengeData,
      feedbackMessage?: string
    ) => {
      updateSelectedVenture(
        (venture) => ({
          ...venture,
          stage1: {
            ...venture.stage1,
            aiStrategyChallenge,
          },
        }),
        feedbackMessage
      );
    },
    [updateSelectedVenture]
  );

  const resetStudio = useCallback(() => {
    const fresh = createInitialStudioState();
    setState(fresh);
    persistState(fresh);
    notifySaved('Workspace reset to clean blank Competition Lab');
  }, [persistState, notifySaved]);

  return {
    state,
    selectedVenture,
    saveFeedback,
    cloudSynced,
    selectVenture,
    setActiveView,
    setSelectedStage,
    saveVentureProfile,
    addBlankAlternative,
    updateAlternative,
    deleteAlternative,
    updateMessMindMatrixRating,
    updateAlternativeMatrixRating,
    saveDifferentiation,
    updateMessMindPosition,
    updateAlternativePosition,
    updateCriticalAssumption,
    updatePositioningStatementDraft,
    savePositioningStatement,
    updateAIStrategyChallenge,
    toggleStage1Completion,
    resetStudio,
  };
}
